#pragma once
#include <cstdint> // Для базового типа uint8_t

namespace shuttle::pal
{
    // Определяет тип окна для внутренней логики диспетчеризации
    enum class WindowType : uint8_t
    {
        Main,          // Главное окно приложения (закрытие гасит приложение)
        ModalDialog,   // Модальное окно (блокирует родителя, не гасит приложение при закрытии)
        DetachedPanel  // Отцепленная панель (не на панели задач, не гасит приложение при закрытии)
    };
}
